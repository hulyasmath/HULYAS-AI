#!/usr/bin/env node

/**
 * Installs a local git pre-commit hook that automatically updates
 * `.railway-build-id` before every commit.
 *
 * This ensures each push to Railway has a fresh build ID so Docker
 * won't reuse stale cached layers.
 */

const fs = require('fs');
const path = require('path');

const projectRoot = path.resolve(__dirname, '..');
const gitDir = path.join(projectRoot, '.git');
const hooksDir = path.join(gitDir, 'hooks');
const hookPath = path.join(hooksDir, 'pre-commit');

if (!fs.existsSync(gitDir)) {
  console.error('❌ .git directory not found. Run this from a git clone.');
  process.exit(1);
}

if (!fs.existsSync(hooksDir)) {
  fs.mkdirSync(hooksDir, { recursive: true });
}

const hookScript = `#!/bin/sh
# Auto-generated by scripts/install-railway-build-hook.js
# Updates .railway-build-id before each commit so Railway sees a fresh build

echo "[pre-commit] Updating Railway build ID..."
npm run update-build-id >/dev/null 2>&1 || {
  echo "[pre-commit] Failed to update build ID"
  exit 1
}

exit 0
`;

fs.writeFileSync(hookPath, hookScript, { mode: 0o755 });

console.log('✅ Installed git pre-commit hook to auto-update .railway-build-id');
console.log('   Hook file:', hookPath);


